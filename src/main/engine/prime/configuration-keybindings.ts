export function primeKeybindingActions(): KeybindingAction[] {
  return definitions.map(([id, description, defaults]) => ({
    id,
    description,
    defaults,
    group: id.startsWith('tui.editor')
      ? 'Editor'
      : id.startsWith('tui.')
        ? 'Terminal'
        : 'Application'
  }))
}
